"""The generated STATE.md of a task store (P23): rendered from the records, never edited by hand.

    render(store, tasks)  the text; pure, so the same records give the same bytes
    write(store)          regenerate it; True when the file changed
    differs(store)        whether the file on disk is not what render gives (the preflight's question)

No clock is read: `created` is the earliest record `created` (else the store README's) and
`updated` the latest record `updated` (else `created`). Lists are ordered for the reader
(SMART-RULE-0027): open tasks and the inbox by identifier (`id_sort_key`), recently completed
newest first by `updated`, then identifier. Open tasks are the records in open/ and recurring/.
A Git conflict in the file is resolved by generating it again.
"""

from __future__ import annotations

import re
from datetime import datetime, timezone

from task_history import parse_stamp
from task_records import Task, id_sort_key, load_tasks, parse_front_matter, write_atomic

CELL_LIMIT = 80
RECENT = 10
EARLIEST = datetime.min.replace(tzinfo=timezone.utc)


def _slug(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")


def state_id(store) -> str:
    if store.kind == "owner":
        return "tasks-state"
    if store.kind == "repository":
        return f"{_slug(store.repository)}-tasks-state"
    node = _slug(str(store.node).removeprefix("/memory/"))
    return f"{node}-private-tasks-state" if store.kind == "pointer-private" else f"{node}-tasks-state"


def _cell(value: str | None) -> str:
    text = " ".join(str(value or "").split()).replace("|", "/")
    return text if len(text) <= CELL_LIMIT else text[:CELL_LIMIT - 3].rstrip() + "..."


def _when(task: Task, key: str) -> datetime:
    return parse_stamp(task.get(key) or "") or EARLIEST


def _readme_created(store) -> str | None:
    readme = store.path / "README.md"
    if not readme.is_file():
        return None
    value = (parse_front_matter(readme.read_text(encoding="utf-8")) or {}).get("created")
    return str(value) if value else None


def render(store, tasks: list[Task]) -> str:
    """The STATE.md text for these records of this store."""
    by_id = sorted(tasks, key=lambda t: id_sort_key(t.tid))
    open_tasks = [t for t in by_id if t.folder in ("open", "recurring")]
    inbox = [t for t in by_id if t.folder == "inbox"]
    # Newest first; equal times keep identifier order (a reverse sort in Python is stable).
    done = sorted((t for t in by_id if t.folder == "completed"), key=lambda t: _when(t, "updated"),
                  reverse=True)[:RECENT]
    stamped = [t for t in tasks if parse_stamp(t.get("created") or "")]
    created = (min(stamped, key=lambda t: _when(t, "created")).get("created") if stamped
               else _readme_created(store))
    touched = [t for t in tasks if parse_stamp(t.get("updated") or "")]
    updated = max(touched, key=lambda t: _when(t, "updated")).get("updated") if touched else created
    lines = [
        "---",
        f"id: {state_id(store)}",
        f"title: Tasks – {store.label}",
        "type: state",
        "schema_version: 0.2",
        "contract: /CONTRACT.md",
        "status: active",
        "generated_by: /shared/skills/tasks",
        f"created: {created or 'null'}",
        f"updated: {updated or 'null'}",
        "---",
        "",
        f"# Tasks – {store.label}",
        "",
        "Generated by `tasks.py state` from the records in this store; never edited by hand. A Git "
        "conflict in this file is resolved by generating it again.",
        "",
        f"## Open tasks ({len(open_tasks)})",
        "",
        "| Task | Status | Priority | Review / waiting on | Title |",
        "|---|---|---|---|---|",
    ]
    for task in open_tasks:
        review = []
        if task.get("next_review"):
            review.append(f"review {task.get('next_review')}")
        if task.get("waiting_on"):
            review.append(f"waiting on {task.get('waiting_on')}")
        lines.append(f"| `{task.tid}` | **{task.get('status') or 'unknown'}** | {_cell(task.get('priority')) or '-'} "
                     f"| {_cell('; '.join(review)) or '-'} | {_cell(task.get('title') or task.tid)} |")
    lines += ["", f"## Inbox ({len(inbox)})", ""]
    lines += [f"- `{t.tid}` {_cell(t.get('title') or t.tid)}" for t in inbox] or ["None."]
    lines += ["", "## Recently completed", ""]
    lines += [f"- `{t.tid}` {_cell(t.get('title') or t.tid)} ({(t.get('updated') or '')[:10] or 'undated'})"
              for t in done] or ["None."]
    return "\n".join(lines) + "\n"


def _records(store) -> list[Task]:
    return load_tasks(store.path, owner=store)


def write(store) -> bool:
    """Regenerate the store's STATE.md; True when the file changed."""
    if not store.reachable:
        raise ValueError(f"{store.label} cannot be written: {store.reason}")
    path = store.path / "STATE.md"
    text = render(store, _records(store))
    if path.is_file() and path.read_text(encoding="utf-8") == text:
        return False
    write_atomic(path, text)
    return True


def differs(store) -> bool:
    path = store.path / "STATE.md"
    current = path.read_text(encoding="utf-8") if path.is_file() else None
    return current != render(store, _records(store))
